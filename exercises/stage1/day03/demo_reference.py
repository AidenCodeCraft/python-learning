# ============================================================
# 1. range 三兄弟：range(stop) / range(start, stop) / range(start, stop, step)
# ============================================================
print("1-a:", list(range(5)))
print("1-b:", list(range(2, 10, 3)))
print("1-c:", list(range(10, 0, -2)))
print("1-d:", list(range(5, 0)))

# ============================================================
# 2. for + enumerate：要下标又要元素
# ============================================================
tasks = ["写代码", "自测", "提交"]
for i, t in enumerate(tasks):
    print("2-a:", i, t)
for i, t in enumerate(tasks, 1):
    print("2-b:", i, t)

# ============================================================
# 3. while + 累加：别忘了让条件变量前进
# ============================================================
total = 0
i = 1
while i <= 5:
    total += i
    i += 1
print("3-a:", total, i)

# ============================================================
# 4. break / continue
# ============================================================
for n in range(1, 10):
    if n == 4:
        break
    print("4-a:", n)

for n in range(1, 8):
    if n % 2 == 0:
        continue
    print("4-b:", n)

# ============================================================
# 5. for ... else：Python 特色 —— 没被 break 打断才走 else
# ============================================================
for n in [1, 3, 5]:
    if n == 4:
        break
else:
    print("5-a: 没找到 4")

for n in [1, 4, 5]:
    if n == 4:
        break
else:
    print("5-b: 没找到 4")

# ============================================================
# 6. zip：两条序列并排走
# ============================================================
names = ["Tom", "Ann", "Bob"]
scores = [90, 85]
print("6-a:", list(zip(names, scores)))
for name, score in zip(names, scores):
    print("6-b:", name, score)

# ============================================================
# 7. 嵌套循环：外圈跑 1 次，内圈跑满 1 轮
# ============================================================
for i in range(1, 3):
    for j in range(1, 3):
        print("7-a:", i, j)

# ============================================================
# 8. 遍历 dict 的三种东西
# ============================================================
user = {"id": 1, "name": "Tom"}
for k in user:
    print("8-a:", k)
for k, v in user.items():
    print("8-b:", k, v)
print("8-c:", list(user.values()))

