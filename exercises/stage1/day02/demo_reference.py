# ============================================================
# 1. 算术运算符：/ // % **
# ============================================================
print("1-a:", 7 / 2)
print("1-b:", 7 // 2)
print("1-c:", -7 // 2)
print("1-d:", 7 % 3)
print("1-e:", -7 % 3)
print("1-f:", 2**10)

# ============================================================
# 2. 比较运算符 + Python 特有的"链式比较"
# ============================================================
print("2-a:", 3 == 3.0)
print("2-b:", 1 < 5 < 3)
print("2-c:", "a" < "b")
print("2-d:", [1, 2] == [1, 2])

# ============================================================
# 3. and / or 返回的是"操作数本身"，不是 True/False
# ============================================================
print("3-a:", 0 or "默认")
print("3-b:", "a" and "b")
print("3-c:", "" or 0 or [] or None or "最后")

# ============================================================
# 4. 短路求值：后面的表达式可能根本不执行
# ============================================================
def boom() -> str:
    print("   >>> boom() 被执行了")
    return "boom"


print("4-a:", False and boom())
print("4-b:", True or boom())
print("4-c:", True and boom())

# ============================================================
# 5. 成员运算符 in / not in
# ============================================================
print("5-a:", "bc" in "abcd")
print("5-b:", 2 in [1, 2, 3])
print("5-c:", "id" in {"id": 1})
print("5-d:", 1 in {"id": 1})

# ============================================================
# 6. 真值判断：哪些值算"假"
# ============================================================
print("6-a:", bool(0), bool(0.0), bool(""), bool([]), bool({}), bool(None))
print("6-b:", bool("0"), bool([0]), bool(-1))

# ============================================================
# 7. if / elif / else：命中即停
# ============================================================
def grade(score: int) -> str:
    if score >= 90:
        return "A"
    elif score >= 80:
        return "B"
    elif score >= 70:
        return "C"
    else:
        return "F"


print("7-a:", grade(95), grade(85), grade(70), grade(10))

# ============================================================
# 8. 三元表达式：一行写完 if/else
# ============================================================
n = 7
print("8-a:", "奇数" if n % 2 else "偶数")

# ============================================================
# 9. 浮点陷阱：不要用 == 比浮点数
# ============================================================
print("9-a:", 0.1 + 0.2)
print("9-b:", 0.1 + 0.2 == 0.3)

# ============================================================
# 10. 真值判断 + in + 条件 的组合（D1 与 D2 的交汇）
# ============================================================
def describe(value: object) -> str:
    if not value:
        return "空"
    if value in ("a", "b"):
        return "在元组里"
    return "其他"


print("10-a:", describe(""), describe("a"), describe("z"))
